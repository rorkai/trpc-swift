import { match, P } from "ts-pattern";

import type { ObjectWireType, TaggedUnionWireType, TagValue, WireProcedure, WireType } from "./ir.ts";
import { elementTypeName, memberName, swiftString, typeName } from "./swift-names.ts";
import { SWIFT_RUNTIME } from "./swift-runtime.ts";

export type GenerateSwiftOptions = {
  /** Swift namespace enum that holds every procedure, e.g. `TRPC` gives `TRPC.Projects.List`. */
  namespace: string;
  /** Shown in the file header so readers know how to regenerate it. */
  regenerateCommand: string;
};

const INDENT = "    ";
const CONFORMANCES = "Codable, Hashable, Sendable";

/**
 * Type names a nested declaration must not take: Swift reads `Foo.Type` and
 * `Foo.Protocol` as the metatype, and a nested `String`, `Hashable`, or
 * `TRPCVoid` would shadow the type or protocol every generated reference to it means.
 */
const RESERVED_TYPE_NAMES = new Set([
  "Type",
  "Protocol",
  "Self",
  "String",
  "Double",
  "Bool",
  "Date",
  "Data",
  "Error",
  "Optional",
  "Array",
  "Dictionary",
  "Decoder",
  "Encoder",
  "Codable",
  "Encodable",
  "Decodable",
  "Hashable",
  "Sendable",
  "CodingKey",
  "RawRepresentable",
  "TRPCVoid",
  "TRPCJSONValue",
  "TRPCProcedure",
  "TRPCProcedureKind",
  "TRPCCoding",
]);

/** A Swift type declaration with the declarations nested inside it. */
type Declaration = { lines: string[]; nested: Declaration[] };

/** Hands out unique names inside one Swift scope, appending a number when sanitised names collide. */
class NameScope {
  private readonly names: Set<string>;
  private readonly reserved: ReadonlySet<string>;

  constructor(reserved: ReadonlySet<string>, taken: Iterable<string> = []) {
    this.reserved = reserved;
    this.names = new Set([...reserved, ...taken]);
  }

  claim(hint: string) {
    const preferred = this.reserved.has(hint) ? `${hint}Value` : hint;
    let name = preferred;
    for (let suffix = 2; this.names.has(name); suffix += 1) {
      name = `${preferred}${suffix}`;
    }
    this.names.add(name);
    return name;
  }
}

/** The nested type declarations of one Swift scope. */
class TypeScope {
  readonly declarations: Declaration[] = [];
  readonly names: NameScope;

  constructor(taken: Iterable<string>) {
    this.names = new NameScope(RESERVED_TYPE_NAMES, taken);
  }
}

/** Renders procedures as Swift `Codable` types grouped under one namespace enum per router segment. */
export function generateSwift(procedures: readonly WireProcedure[], options: GenerateSwiftOptions) {
  const sorted = procedures.toSorted((a, b) => compareCodeUnits(a.path, b.path));
  const swiftPaths = assignSwiftPaths(sorted.map((procedure) => procedure.path));
  const namespaces = [...new Set(sorted.flatMap((procedure) => routerPrefixes(procedure.path)))].toSorted();

  const sections = [
    `// Generated by trpc-swift. Do not edit by hand.\n// Regenerate with: ${options.regenerateCommand}\n\nimport Foundation`,
    SWIFT_RUNTIME,
    `public enum ${options.namespace} {}`,
    ...namespaces.map((namespace) => {
      const { parent, name } = swiftParentAndName(swiftPaths, namespace, options.namespace);
      return `extension ${parent} {\n${INDENT}public enum ${name} {}\n}`;
    }),
    ...sorted.map((procedure) => {
      const { parent, name } = swiftParentAndName(swiftPaths, procedure.path, options.namespace);
      return renderProcedure(procedure, parent, name);
    }),
  ];
  return `${sections.join("\n\n")}\n`;
}

/** Code-unit order, as `toSorted()` uses, so the output does not depend on the machine's ICU data or locale. */
function compareCodeUnits(a: string, b: string) {
  if (a < b) {
    return -1;
  }
  return a > b ? 1 : 0;
}

/** `a.b.c` → `["a", "a.b"]`, the routers that contain a procedure. */
function routerPrefixes(path: string) {
  const segments = path.split(".");
  return segments.slice(0, -1).map((_, index) => segments.slice(0, index + 1).join("."));
}

/**
 * Names every router and procedure segment once, per parent, so `foo_bar` and
 * `fooBar` under one router do not both become `FooBar`.
 */
function assignSwiftPaths(paths: readonly string[]) {
  const scopes = new Map<string, NameScope>();
  const names = new Map<string, string>();
  for (const path of paths) {
    const segments = path.split(".");
    segments.forEach((segment, index) => {
      const key = segments.slice(0, index + 1).join(".");
      if (names.has(key)) {
        return;
      }
      const parent = segments.slice(0, index).join(".");
      const scope = scopes.get(parent) ?? new NameScope(RESERVED_TYPE_NAMES);
      scopes.set(parent, scope);
      names.set(key, scope.claim(typeName(segment)));
    });
  }
  return names;
}

function swiftParentAndName(swiftPaths: ReadonlyMap<string, string>, path: string, namespace: string) {
  const segments = path.split(".");
  const swiftSegments = segments.map((_, index) => swiftPaths.get(segments.slice(0, index + 1).join(".")) ?? "");
  return { parent: [namespace, ...swiftSegments.slice(0, -1)].join("."), name: swiftSegments.at(-1) ?? "" };
}

function renderProcedure(procedure: WireProcedure, parent: string, name: string) {
  const scope = new TypeScope([name, "Input", "Output", "CodingKeys"]);
  const lines = [
    `public enum ${name}: TRPCProcedure {`,
    `${INDENT}public static let path = ${swiftString(procedure.path)}`,
    `${INDENT}public static let kind = TRPCProcedureKind.${procedure.kind}`,
    ...topLevelType(procedure.input, "Input", scope).map(indent),
    ...topLevelType(procedure.output, "Output", scope).map(indent),
    ...scope.declarations.flatMap((declaration) => ["", ...renderDeclaration(declaration).map(indent)]),
    "}",
  ];
  return `extension ${parent} {\n${lines.map(indent).join("\n")}\n}`.replaceAll(/[ ]+$/gm, "");
}

/** `Input`/`Output` become the declared type itself when it is named, else a typealias. */
function topLevelType(wire: WireType, role: "Input" | "Output", scope: TypeScope) {
  if (isNamed(wire)) {
    scope.declarations.push(declare(wire, role));
    return [];
  }
  return [`public typealias ${role} = ${typeReference(wire, `${role}Payload`, scope)}`];
}

function typeReference(wire: WireType, hint: string, scope: TypeScope): string {
  return match(wire)
    .with({ kind: "string" }, () => "String")
    .with({ kind: "number" }, () => "Double")
    .with({ kind: "boolean" }, () => "Bool")
    .with({ kind: "date" }, () => "Date")
    .with({ kind: "void" }, () => "TRPCVoid")
    .with({ kind: "json" }, () => "TRPCJSONValue")
    .with({ kind: "optional" }, ({ inner }) => `${typeReference(inner, hint, scope)}?`)
    .with({ kind: "array" }, ({ element }) => `[${typeReference(element, elementTypeName(hint), scope)}]`)
    .with({ kind: "record" }, ({ value }) => `[String: ${typeReference(value, `${hint}Value`, scope)}]`)
    .with({ kind: P.union("object", "taggedUnion", "stringEnum") }, (named) => {
      const name = scope.names.claim(hint);
      scope.declarations.push(declare(named, name));
      return name;
    })
    .exhaustive();
}

type NamedWireType = Extract<WireType, { kind: "object" | "taggedUnion" | "stringEnum" }>;

function declare(wire: NamedWireType, name: string) {
  return match(wire)
    .with({ kind: "object" }, (object) => declareStruct(object, name))
    .with({ kind: "taggedUnion" }, (union) => declareTaggedUnion(union, name))
    .with({ kind: "stringEnum" }, ({ values }) => declareStringEnum(values, name))
    .exhaustive();
}

function declareStruct(wire: ObjectWireType, name: string): Declaration {
  const scope = new TypeScope([name, "CodingKeys"]);
  const members = new NameScope(new Set());
  const fields = wire.properties.map((property) => ({
    wireName: property.name,
    swiftName: members.claim(memberName(property.name)),
    type: typeReference(property.type, typeName(property.name), scope),
    // `T | null` must still send its key: synthesised encoding omits nil, which a required nullable input rejects.
    sendsNull: property.type.kind === "optional" && !property.type.omittable,
  }));
  // Only a key the wire may leave out defaults to nil; a required `T | null` must be chosen at the call site.
  const parameters = fields.map(
    (field) => `${field.swiftName}: ${field.type}${field.type.endsWith("?") && !field.sendsNull ? " = nil" : ""}`,
  );
  const renamed = fields.some((field) => field.swiftName !== field.wireName);
  const encodesNull = fields.some((field) => field.sendsNull);
  const lines = [
    `public struct ${name}: ${CONFORMANCES} {`,
    ...fields.map((field) => `${INDENT}public var ${field.swiftName}: ${field.type}`),
    ...(fields.length > 0 ? [""] : []),
    `${INDENT}public init(${parameters.join(", ")}) {`,
    ...fields.map((field) => `${INDENT}${INDENT}self.${field.swiftName} = ${field.swiftName}`),
    `${INDENT}}`,
    ...(renamed || encodesNull
      ? [
          "",
          `${INDENT}private enum CodingKeys: String, CodingKey {`,
          ...fields.map(
            (field) =>
              `${INDENT}${INDENT}case ${field.swiftName}${field.swiftName === field.wireName ? "" : ` = ${swiftString(field.wireName)}`}`,
          ),
          `${INDENT}}`,
        ]
      : []),
    ...(encodesNull
      ? [
          "",
          `${INDENT}public func encode(to encoder: any Encoder) throws {`,
          `${INDENT}${INDENT}var container = encoder.container(keyedBy: CodingKeys.self)`,
          ...fields.map(
            (field) =>
              `${INDENT}${INDENT}try container.${field.type.endsWith("?") && !field.sendsNull ? "encodeIfPresent" : "encode"}(self.${field.swiftName}, forKey: .${field.swiftName})`,
          ),
          `${INDENT}}`,
        ]
      : []),
  ];
  return { lines, nested: scope.declarations };
}

/**
 * A string union decodes into a `RawRepresentable` struct rather than a Swift
 * enum, so a value the server adds later still decodes on a client that
 * predates it.
 */
function declareStringEnum(values: readonly string[], name: string): Declaration {
  const members = new NameScope(new Set(["rawValue", "init"]));
  return {
    lines: [
      `public struct ${name}: RawRepresentable, ${CONFORMANCES} {`,
      `${INDENT}public let rawValue: String`,
      "",
      `${INDENT}public init(rawValue: String) {`,
      `${INDENT}${INDENT}self.rawValue = rawValue`,
      `${INDENT}}`,
      "",
      ...values.map(
        (value) =>
          `${INDENT}public static let ${members.claim(memberName(value))} = Self(rawValue: ${swiftString(value)})`,
      ),
    ],
    nested: [],
  };
}

/**
 * Objects told apart by a literal property decode as an enum. A string tag
 * the client does not know decodes as the fallback case; a boolean tag is
 * exhaustive. The payload structs leave the tag out, so the encoded tag always
 * comes from the case and cannot contradict it.
 */
function declareTaggedUnion(wire: TaggedUnionWireType, name: string): Declaration {
  const isBoolean = wire.variants.every((variant) => variant.tagValue.kind === "boolean");
  // `ok: true | false` reads best as `.ok` and `.notOk`.
  const label = (tagValue: TagValue) =>
    match(tagValue)
      .with({ kind: "string" }, ({ value }) => value)
      .with({ kind: "boolean", value: true }, () => wire.tag)
      .with({ kind: "boolean", value: false }, () => `not ${wire.tag}`)
      .exhaustive();
  const literal = (tagValue: TagValue) =>
    tagValue.kind === "string" ? swiftString(tagValue.value) : String(tagValue.value);
  const cases = new NameScope(new Set());
  const caseNames = wire.variants.map((variant) => cases.claim(memberName(label(variant.tagValue))));
  const fallback = isBoolean ? undefined : cases.claim("unknown");
  const scope = new TypeScope([name, "TagCodingKeys", ...caseNames, ...(fallback == null ? [] : [fallback])]);
  const variants = wire.variants.map((variant, index) => {
    const variantLabel = label(variant.tagValue);
    return {
      literal: literal(variant.tagValue),
      caseName: caseNames[index] ?? "",
      // `2fa-method` would name both the case and its payload `_2faMethod`; prefixing the tag key keeps the type readable.
      typeName: typeReference(
        { ...variant.type, properties: variant.type.properties.filter((property) => property.name !== wire.tag) },
        /^[0-9]/.test(variantLabel) ? typeName(`${wire.tag} ${variantLabel}`) : typeName(variantLabel),
        scope,
      ),
    };
  });
  const tagType = isBoolean ? "Bool" : "String";
  const lines = [
    `public enum ${name}: ${CONFORMANCES} {`,
    ...variants.map((variant) => `${INDENT}case ${variant.caseName}(${variant.typeName})`),
    ...(fallback == null ? [] : [`${INDENT}case ${fallback}(tag: String)`]),
    "",
    `${INDENT}private enum TagCodingKeys: String, CodingKey {`,
    `${INDENT}${INDENT}case tag = ${swiftString(wire.tag)}`,
    `${INDENT}}`,
    "",
    `${INDENT}public init(from decoder: any Decoder) throws {`,
    `${INDENT}${INDENT}let tag = try decoder.container(keyedBy: TagCodingKeys.self).decode(${tagType}.self, forKey: .tag)`,
    `${INDENT}${INDENT}switch tag {`,
    ...variants.map(
      (variant) =>
        `${INDENT}${INDENT}case ${variant.literal}: self = .${variant.caseName}(try ${variant.typeName}(from: decoder))`,
    ),
    ...(fallback == null ? [] : [`${INDENT}${INDENT}default: self = .${fallback}(tag: tag)`]),
    `${INDENT}${INDENT}}`,
    `${INDENT}}`,
    "",
    `${INDENT}public func encode(to encoder: any Encoder) throws {`,
    `${INDENT}${INDENT}let tag: ${tagType}`,
    `${INDENT}${INDENT}switch self {`,
    ...variants.flatMap((variant) => [
      `${INDENT}${INDENT}case let .${variant.caseName}(value):`,
      `${INDENT}${INDENT}${INDENT}try value.encode(to: encoder)`,
      `${INDENT}${INDENT}${INDENT}tag = ${variant.literal}`,
    ]),
    ...(fallback == null
      ? []
      : [`${INDENT}${INDENT}case let .${fallback}(unknownTag):`, `${INDENT}${INDENT}${INDENT}tag = unknownTag`]),
    `${INDENT}${INDENT}}`,
    `${INDENT}${INDENT}var container = encoder.container(keyedBy: TagCodingKeys.self)`,
    `${INDENT}${INDENT}try container.encode(tag, forKey: .tag)`,
    `${INDENT}}`,
  ];
  return { lines, nested: scope.declarations };
}

function isNamed(wire: WireType) {
  return wire.kind === "object" || wire.kind === "taggedUnion" || wire.kind === "stringEnum";
}

function renderDeclaration(declaration: Declaration): string[] {
  return [
    ...declaration.lines,
    ...declaration.nested.flatMap((nested) => ["", ...renderDeclaration(nested).map(indent)]),
    "}",
  ];
}

function indent(line: string) {
  return line.length === 0 ? line : `${INDENT}${line}`;
}
